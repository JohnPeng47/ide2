import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtemp, rm, readFile } from 'node:fs/promises';
import { tmpdir, homedir } from 'node:os';
import { createServer } from 'node:net';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { randomUUID } from 'node:crypto';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import { seedMappingFixture } from '../support/browser-mapping-fixture.mjs';
const { evaluate, waitFor, waitForSelector, withHeadlessBrowser, captureScreenshot } = await import(pathToFileURL(path.join(homedir(), '.codex/skills/front-end/browser-test.mjs')).href);
const root = await mkdtemp(path.join(tmpdir(), 'agent-diagramming-'));
let server, client;
try {
  await seedMappingFixture(root, { ascii: '[Existing]', nodes: [] });
  const port = await new Promise(resolve => { const socket = createServer(); socket.listen(0, '127.0.0.1', () => { const port = socket.address().port; socket.close(() => resolve(port)); }); });
  const url = `http://127.0.0.1:${port}`;
  server = spawn(process.execPath, ['scripts/dev/start-server.mjs', 'preview', '--host', '127.0.0.1', '--port', String(port), '--strictPort'],
    { cwd: process.cwd(), env: { ...process.env, NEW_DIAGRAM_PROJECT_ROOT: root, NEW_DIAGRAMS_DIR: path.join(root, '.diagrams'), NEW_DIAGRAM_AGENT: 'fake' }, stdio: ['ignore','ignore','pipe'] });
  let errors = ''; server.stderr.on('data', chunk => { errors += chunk; });
  await waitFor(async () => (await fetch(url).catch(() => null))?.ok, { timeoutMs: 20000 }).catch(error => { throw new Error(`${error}\n${errors}`); });
  client = new Client({ name: 'mapping-browser-check', version: '1' });
  await client.connect(new StdioClientTransport({ command: process.execPath, args: ['node_modules/tsx/dist/cli.mjs','scripts/mapping/mcp.ts',url], cwd: process.cwd(), stderr: 'pipe' }));
  const call = async (name, args, error = false) => {
    console.log('MCP call', name, args.code?.slice(0, 70) ?? args.operation ?? '');
    const result = await client.callTool({ name, arguments: args });
    console.log('MCP result', name, result.isError ? 'error' : 'ok');
    const value = JSON.parse(result.content[0].text);
    assert.equal(Boolean(result.isError), error, JSON.stringify(value));
    return value;
  };
  const exec = args => call('exec', { requestId: randomUUID(), ...args });
  assert.deepEqual((await client.listTools()).tools.map(tool => tool.name).sort(), ['accept_diagram_change_session','cancel-diagram-edit','canvas-api-search','create_diagram_change_session','diagram-search','draw_diagram','edit-diagram','edit-diagram-status','exec','save_diagram','set_diagram_source_mappings','update_diagram_change_session']);
  assert.ok((await call('canvas-api-search', { query: 'move' })).some(method => method.name === 'nodes.move'));
  assert.ok((await call('canvas-api-search', { query: 'copyDocument' })).some(method => method.name === 'canvas.copyDocument'));
  await withHeadlessBrowser({ url: `${url}/mapping`, width: 1800, height: 1100, chromePath: process.env.CHROME_PATH, arguments: ['--disable-gpu', ...(process.platform === 'linux' ? ['--no-sandbox'] : [])] }, async ({ cdp }) => {
    const send = cdp.send.bind(cdp);
    cdp.send = (method, params) => {
      let timer;
      return Promise.race([send(method, params), new Promise((_, reject) => { timer = setTimeout(() => reject(new Error(`CDP timeout: ${method}`)), 15000); })]).finally(() => clearTimeout(timer));
    };
    await cdp.send('Page.enable');
    cdp.on('Page.javascriptDialogOpening', () => void cdp.send('Page.handleJavaScriptDialog', {accept:true}));
    await waitForSelector(cdp, '[data-grid-box="overview"]');
    let available;
    await waitFor(async () => { available = (await exec({code:'return canvas.list();'})).value; return available[0]?.documents.length; });
    const canvas = available[0];
    const attached = (await exec({ code: `return canvas.attach(${JSON.stringify({canvasId:canvas.canvasId,documentId:canvas.documents[0].documentId})});` })).value;
    const sessionId = attached.sessionId;
    const before = (await exec({ sessionId, code: 'return nodes.list();' })).value;
    const args = { sessionId, requestId: randomUUID(), expectedVersion: before.version, ascii: 'Agent service\n+-- Read\n`-- Write', structureKind: 'tree', position: { column: 0, row: 0 } };
    const drawn = await call('draw_diagram', args);
    const node = drawn.nodes.find(node => node.kind === 'diagram' && node.content.ascii.startsWith('Agent service'));
    assert.ok(node);
    const boxId = node.boxId;
    await waitForSelector(cdp, `[data-grid-box="${boxId}"]`);
    assert.ok(await evaluate(cdp, 'Number(document.querySelector("[data-grid-box=overview]").dataset.gridColumn) > 0'));
    assert.deepEqual(await call('draw_diagram', args), drawn);
    assert.equal(await evaluate(cdp, `document.querySelectorAll('[data-grid-box="${boxId}"]').length`), 1);
    const read = await call('diagram-search', { operation:'read', sessionId, nodeId:node.id });
    assert.equal(read.node.content.ascii, args.ascii);
    assert.equal(read.node.content.structure.kind, 'tree');
    const stale = await call('draw_diagram', { ...args, requestId: randomUUID() }, true);
    assert.match(stale.error, /VERSION_CONFLICT/);
    const partial = await call('exec', { sessionId, expectedVersion: read.version, requestId: randomUUID(), code: 'nodes.draw({ascii:"Committed before error"}); throw new Error("stop");' }, true);
    assert.match(partial.error, /stop/);
    assert.equal((await exec({ sessionId, code:'return nodes.list();' })).value.nodes.filter(node => node.kind === 'diagram').length, 3);
    const click = async selector => {
      const p = await evaluate(cdp, `(() => {const r=document.querySelector(${JSON.stringify(selector)}).getBoundingClientRect();return {x:r.left+r.width/2,y:r.top+r.height/2};})()`);
      await cdp.send('Input.dispatchMouseEvent', {type:'mousePressed', ...p, button:'left', buttons:1, clickCount:1});
      await cdp.send('Input.dispatchMouseEvent', {type:'mouseReleased', ...p, button:'left', buttons:0, clickCount:1});
    };
    await click('.mapping-grid-tools button:first-child');
    await waitFor(async () => !(await evaluate(cdp, `document.querySelector('.mapping-poc-ascii')?.textContent.includes('Committed before error')`)));
    await click('.mapping-grid-tools button:first-child');
    await waitFor(async () => !(await evaluate(cdp, `Boolean(document.querySelector('[data-grid-box="${boxId}"]'))`)));
    await click('.mapping-grid-tools button:nth-child(2)');
    await waitForSelector(cdp, `[data-grid-box="${boxId}"]`);
    const batchVersion = (await exec({sessionId,code:'return nodes.list();'})).version;
    const batch = await exec({sessionId, expectedVersion:batchVersion, code:'const a = nodes.draw({ascii:"[Batch A]",position:{column:30,row:10}}); const b = nodes.draw({ascii:"[Batch B]",position:{column:45,row:10}}); return [nodes.get({nodeId:a.id}).id,b.id];'});
    assert.equal(batch.value.length, 2);
    for (const id of batch.value) await waitForSelector(cdp, `[data-grid-box="${id.slice(5)}"]`);
    await click('.mapping-grid-tools button:first-child');
    await waitFor(async () => !(await evaluate(cdp, `Boolean(document.querySelector('[data-grid-box="${batch.value[1].slice(5)}"]'))`)));
    assert.ok(await evaluate(cdp, `Boolean(document.querySelector('[data-grid-box="${batch.value[0].slice(5)}"]'))`));
    await click('.mapping-grid-tools button:first-child');
    await waitFor(async () => !(await evaluate(cdp, `Boolean(document.querySelector('[data-grid-box="${batch.value[0].slice(5)}"]'))`)));
    assert.equal((await exec({sessionId,code:'return nodes.list();'})).value.nodes.filter(node => node.kind === 'diagram').length, 2);
    const version = (await exec({sessionId,code:'return nodes.list();'})).version;
    const saved = await call('save_diagram', {sessionId, requestId:randomUUID(), expectedVersion:version, nodeId:node.id, name:'Agent proposal'});
    await waitForSelector(cdp, `[data-project-diagram="${saved.representationId}"]`);
    const found = await call('diagram-search', {operation:'search',mode:'node',query:'Read'});
    assert.ok(found.hits.some(hit => hit.representationId === saved.representationId));
    const persisted = await call('diagram-search', {operation:'read',representationId:saved.representationId});
    assert.equal(persisted.revision.ascii, args.ascii);
    assert.equal(persisted.revision.content.kind, 'canvas-history');
    const history = persisted.revision.content.history;
    const overviewRevision = history.snapshots[history.headId].diagramBindings.overview;
    assert.equal(history.diagramRevisions[overviewRevision].diagram.content.ascii, args.ascii);
    const created = (await exec({code:`return canvas.createDocument(${JSON.stringify({canvasId:canvas.canvasId,name:'Unsaved proposal'})});`})).value;
    await waitFor(async () => (await exec({sessionId:created.sessionId,code:'return nodes.list();'})).value.nodes.length > 0);
    const replaced = await call('draw_diagram', {sessionId:created.sessionId,requestId:randomUUID(),expectedVersion:created.version,nodeId:'grid:overview',ascii:'[New document]'});
    const savedDoc = await call('save_diagram', {sessionId:created.sessionId,requestId:randomUUID(),expectedVersion:replaced.version,name:'Saved proposal'});
    await waitForSelector(cdp, `[data-project-diagram="${savedDoc.representationId}"]`);
    const sourceVersion = (await exec({sessionId:created.sessionId,code:'return nodes.list();'})).version;
    const copyAscii = 'Unsaved source\n\n`-- Keep blank separator';
    const prepared = await exec({sessionId:created.sessionId,expectedVersion:sourceVersion,code:`
      nodes.replace({nodeId:'grid:overview',ascii:${JSON.stringify(copyAscii)},structureKind:'tree'});
      const other=nodes.draw({ascii:'Related diagram',position:{column:40,row:8}});
      const source=nodes.get({nodeId:'grid:overview'});
      edges.create({source:{kind:'content-node',displayNodeId:source.id,contentNodeId:source.contentNodes[0].id,revisionId:source.content.revisionId},
        target:{kind:'box',displayNodeId:other.id},appearance:{color:'#88c0d0',lineStyle:'solid',label:{text:'Related',position:{x:250,y:80}}}});
      return {nodes:nodes.list(),edges:edges.list()};`});
    const copyRequest = {requestId:randomUUID(),code:`return canvas.copyDocument(${JSON.stringify({canvasId:canvas.canvasId,documentId:created.documentId,name:'Independent copy',expectedVersion:prepared.transaction.version})});`};
    const copyResult = await exec(copyRequest), copy = copyResult.value;
    assert.deepEqual(await exec(copyRequest), copyResult);
    assert.notEqual(copy.documentId, created.documentId); assert.equal(copy.version, 0);
    await waitFor(async () => await evaluate(cdp, 'document.querySelector(".mapping-document-view:not([hidden]) .mapping-poc-ascii")?.textContent.includes("Unsaved source")'));
    await waitFor(async () => await evaluate(cdp, 'document.querySelector(".mapping-document-view:not([hidden]) .mapping-grid-tools button:first-child")?.disabled'));
    const copiedState = (await exec({sessionId:copy.sessionId,code:'return {nodes:nodes.list(),edges:edges.list()};'})).value;
    const contents = state => state.nodes.nodes.filter(n=>n.kind==='diagram').map(n=>({id:n.id,content:n.content}));
    assert.deepEqual(contents(copiedState), contents(prepared.value));
    assert.deepEqual(copiedState.edges.edges, prepared.value.edges.edges);
    assert.equal(copiedState.nodes.nodes.find(n=>n.id==='grid:overview').content.ascii, copyAscii);
    await exec({sessionId:copy.sessionId,expectedVersion:0,code:'return nodes.replace({nodeId:"grid:overview",ascii:"Changed only in copy"});'});
    await waitFor(async () => await evaluate(cdp, 'document.querySelector(".mapping-document-view:not([hidden]) .mapping-poc-ascii")?.textContent.includes("Changed only in copy")'));
    await click('.mapping-document-view:not([hidden]) .mapping-grid-tools button:first-child');
    await waitFor(async () => await evaluate(cdp, 'document.querySelector(".mapping-document-view:not([hidden]) .mapping-poc-ascii")?.textContent.includes("Unsaved source")'));
    await click('.mapping-document-view:not([hidden]) .mapping-grid-tools button:nth-child(2)');
    await waitFor(async () => await evaluate(cdp, 'document.querySelector(".mapping-document-view:not([hidden]) .mapping-poc-ascii")?.textContent.includes("Changed only in copy")'));
    const sourceAfter = (await exec({sessionId:created.sessionId,code:'return {nodes:nodes.list(),edges:edges.list()};'})).value;
    assert.deepEqual(sourceAfter, prepared.value);
    const copyVersion = (await exec({sessionId:copy.sessionId,code:'return nodes.list();'})).version;
    const savedCopy = await call('save_diagram', {sessionId:copy.sessionId,requestId:randomUUID(),expectedVersion:copyVersion,name:'Independent copy'});
    assert.notEqual(savedCopy.representationId, savedDoc.representationId);
    await waitForSelector(cdp, `[data-project-diagram="${savedCopy.representationId}"]`);
    const savedSource = await call('diagram-search', {operation:'read',representationId:savedDoc.representationId});
    assert.equal(savedSource.revision.ascii, '[New document]');
    await captureScreenshot(cdp, {output:path.join(root,'agent-diagramming.png')});
    let reloaded = false;
    cdp.on('Page.loadEventFired', () => { reloaded = true; });
    await cdp.send('Page.reload');
    await waitFor(() => reloaded);
    await waitFor(async () => await evaluate(cdp, 'document.querySelector(".mapping-document-view:not([hidden]) .mapping-poc-ascii")?.textContent.includes("Changed only in copy")'));
    // Workspace restore selects its saved active document. Use the explorer to switch to the source.
    await click(`[data-project-diagram="${savedDoc.representationId}"]`);
    await waitFor(async () => await evaluate(cdp, 'document.querySelector(".mapping-document-view:not([hidden]) .mapping-poc-ascii")?.textContent.includes("Unsaved source")'));
    await click(`[data-project-diagram="${savedCopy.representationId}"]`);
    await waitFor(async () => await evaluate(cdp, 'document.querySelector(".mapping-document-view:not([hidden]) .mapping-poc-ascii")?.textContent.includes("Changed only in copy")'));
    const catalog = JSON.parse(await readFile(path.join(root,'.diagrams/canvases/catalog.json'),'utf8'));
    assert.equal(catalog.representations[savedDoc.representationId].status, 'settled');
    console.log('MCP search/read, draw, layout, retry, conflict, partial failures, per-edit undo/redo, standalone save, document copy with unsaved content/blank lines/edges, independent undo/save, explorer, and reload passed');
  });
} finally {
  await client?.close(); server?.kill('SIGTERM'); await rm(root,{recursive:true,force:true});
}
